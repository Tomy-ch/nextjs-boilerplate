/**
 * 読み手がシェルへ貼る値に許す文字集合。
 *
 * @remarks
 * PR の失敗コメントと撮り直しの完了コメントは、**読み手がそのまま端末へ貼るコマンド**を並べます
 * （[0153](../../docs/adr/0153-ci-configuration.md) §5）。そこへ載る値 —— ブランチ名・story の
 * id・画面の名前 —— はいずれも PR の側が決められるので、集合の外を含む値は行ごと落とします。
 * 引用符で囲むだけでは足りません。同じ集合が、値を markdown として描かせても記法にならないこと
 * も担保しています。
 *
 * **集合は 1 つでなければ意味を持ちません。** 判定を各ワークフローが書き起こすと、片方だけが
 * 広がったことに誰も気付けません。ADR が「同じ集合」と言うのはこの不変条件のことなので、
 * 綴りをここ 1 箇所に置き、全員がこれを呼びます。
 */

/** 許す文字。英数と、経路・版・区切りに要る記号だけ。 */
const ACCEPTED_PATTERN = /^[A-Za-z0-9/._,-]*$/;

/**
 * その値がシェルへ貼れないものを含むか。
 *
 * @remarks
 * 落とす側で判定します。「安全なら通す」ではなく「1 つでも外れたら行ごと落とす」向きなので、
 * 呼ぶ側は真を受け取ったらその節を出しません。
 *
 * @param values - 貼る値。1 つでも外れれば真を返す
 */
export function containsUnsafe(...values: readonly string[]): boolean {
  return values.some((value) => !ACCEPTED_PATTERN.test(value));
}
